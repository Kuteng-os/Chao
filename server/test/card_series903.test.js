test('custom series names appear in filters and search, never in card face/name; escaped editor options',()=>{
 const catalog={current:3,available:[1,2,3],entries:[{id:1,name:'初始篇'},{id:2,name:'第二期'},{id:3,name:'<新篇> & "'}]};
 const record={series:3,definition:{...freshCard(),faction_id:FACTION_ID,name:'原卡名'},rules_text:'抽1张牌'};
 assert.equal(seriesEntries(catalog).at(-1).name,'<新篇> & "');
 assert.match(seriesOptions(catalog,3),/value="3" selected/);assert(!seriesOptions(catalog,3).includes('<新篇>'));
 assert.match(filtersUI(filterDefaults,[record],[],[],'',catalog),/&lt;新篇&gt;/);
 assert.equal(filterCards([record],{...filterDefaults,q:'新篇'},{series:catalog}).length,1);
 assert(!cardFace(record,[]).includes('新篇'));assert.equal(record.definition.name,'原卡名');
});
