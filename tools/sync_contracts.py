import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
def load(name):return json.loads((root/'docs/cards'/name).read_text(encoding='utf-8'))
values={'CARD_JSON':load('card.schema.json'),'KEYWORD_JSON':load('keyword.schema.json'),'BUILTINS_JSON':[load('examples/keywords/core_blitz.json'),load('examples/keywords/core_guard.json'),load('examples/keywords/standard_heavy_armor.json'),load('examples/keywords/standard_heavy_armor_v2.json')]+load('builtin_keywords.json')}
lines=['extends RefCounted','# Generated by tools/sync_contracts.py from docs/cards; no card pool is bundled.']
for name,value in values.items():lines.append('const '+name+' = '+json.dumps(json.dumps(value,ensure_ascii=False,separators=(',',':')),ensure_ascii=False))
(root/'scripts/core/contracts.gd').write_text('\n'.join(lines)+'\n',encoding='utf-8')
