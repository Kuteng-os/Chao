// Regenerates scripts/core/contracts.gd from docs/cards. Node port of tools/sync_contracts.py, which needs Python 3.
// node tools/sync_contracts.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = name => JSON.parse(readFileSync(join(root, 'docs/cards', name), 'utf8'));
const values = {
  CARD_JSON: load('card.schema.json'),
  KEYWORD_JSON: load('keyword.schema.json'),
  BUILTINS_JSON: [load('examples/keywords/core_blitz.json'), load('examples/keywords/core_guard.json'), load('examples/keywords/standard_heavy_armor.json'), load('examples/keywords/standard_heavy_armor_v2.json'), ...load('builtin_keywords.json')],
};
// Python's json.dumps escapes the same characters as JSON.stringify once ensure_ascii is off, so both generators agree.
const lines = ['extends RefCounted', '# Generated by tools/sync_contracts.py from docs/cards; no card pool is bundled.'];
for (const [name, value] of Object.entries(values)) lines.push(`const ${name} = ${JSON.stringify(JSON.stringify(value))}`);
writeFileSync(join(root, 'scripts/core/contracts.gd'), lines.join('\n') + '\n');
console.log('contracts.gd regenerated');
